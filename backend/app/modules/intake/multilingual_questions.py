def get_localized_question(
    key_or_id: str,
    target_lang: str = "en",
    default_text: str = ""
) -> str:
    """
    Returns high-precision native translated question for Indian languages.
    Falls back to default_text or English if language code is missing.
    """
    lang = (target_lang or "en").lower().strip()
    clean_key = key_or_id.lower().strip()

    if lang == "en":
        # Check if direct key exists
        entry = QUESTION_TRANSLATIONS.get(clean_key)
        if entry and "en" in entry:
            return entry["en"]
        return default_text or key_or_id

    # Lookup in catalog by key/id
    if clean_key.startswith("ayur_"):
        domain = clean_key.replace("ayur_", "")
        clean_key = f"ayur_{domain}"

    entry = QUESTION_TRANSLATIONS.get(clean_key)
    if entry and lang in entry:
        return entry[lang]

    # Try matching by default English text if key didn't match
    if default_text:
        for k, v in QUESTION_TRANSLATIONS.items():
            if v.get("en", "").lower().strip() == default_text.lower().strip():
                if lang in v:
                    return v[lang]

    return default_text or key_or_id


def get_localized_options(
    question_id: str,
    options: list,
    target_lang: str = "en"
) -> list:
    """
    Translates option labels for structured single-choice questions into the target language.
    """
    lang = (target_lang or "en").lower().strip()
    if not options or lang == "en":
        return options

    localized = []
    for opt in options:
        if isinstance(opt, str):
            trans = OPTION_TRANSLATIONS.get(opt, {}).get(lang, opt)
            localized.append(trans)
        elif isinstance(opt, dict):
            opt_copy = dict(opt)
            val = opt.get("value", "")
            orig_label = opt.get("label", "")
            trans = (
                OPTION_TRANSLATIONS.get(val, {}).get(lang) or
                OPTION_TRANSLATIONS.get(orig_label, {}).get(lang)
            )
            if trans:
                opt_copy["label"] = trans
            localized.append(opt_copy)
        else:
            localized.append(opt)

    return localized

